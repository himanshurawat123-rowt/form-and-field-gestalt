function createRailProduct(spec: ProductSpec): RailProduct {
  const colorway: ProductColorway = { name: spec.shade, swatch: spec.color };

  return {
    id: spec.id,
    name: spec.name,
    description: spec.description,
    category: spec.category,
    price: spec.price,
    tag: `RAIL / ${String(specs.indexOf(spec) + 1).padStart(2, "0")}`,
    kind: spec.kind,
    color: spec.color,
    details: [spec.description, "Designed for everyday wear", "Considered, easy fit"],
    sizes: spec.category === "bottoms" ? ["28", "30", "32", "34", "36"] : sizes,
    colorways: [colorway],
    railCategories: [spec.railCategory],
  };
}

